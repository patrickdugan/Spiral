"""One cooperative offboard from the existing owned fixture, with no resend."""
import json
from bootstrap import core
from launch import bark
from fund import mine
from attest import DEST, save
from observe import snapshot
from pay import action

CLAIM = 'e59ba9240fb4294d026d9d2d31b965fabcd23632d4a058cf77882ed56044324e:0'


def main():
    if core('getblockchaininfo')['chain'] != 'regtest':
        raise RuntimeError('owned regtest required')
    if (DEST / 'offboard-before.json').exists():
        raise RuntimeError('offboard previously started; reconcile existing attempt')
    if core('getrawmempool'):
        raise RuntimeError('unrelated pending transaction')
    before = snapshot('offboard-before')
    claim = next(v for v in before['bark_vtxos'] if v['id'] == CLAIM)
    assert claim['state']['type'] == 'spendable' and claim['amount_sat'] == 18632
    save('offboard-intent.json', {'claim_id': CLAIM, 'amount_sat': 18632,
        'destination': 'existing Bark on-chain wallet, generated by offboard command',
        'external_funding_sat': 0, 'other_claims': 'remain outstanding'})
    result = action('offboard-18632', lambda: json.loads(bark('offboard', '--vtxo', CLAIM, '--no-sync').stdout))
    txid = result['offboard_txid']
    assert txid in core('getrawmempool')
    snapshot('offboard-broadcast')
    action('offboard-confirm', lambda: {'height': mine(3)})
    action('offboard-client-sync', lambda: json.loads(bark('balance').stdout))
    snapshot('offboard-confirmed')


if __name__ == '__main__':
    main()
