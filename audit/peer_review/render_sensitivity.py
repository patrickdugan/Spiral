"""Render the compact paper table from the retained post hoc sensitivity JSON."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
data = json.loads((ROOT / 'audit/peer_review/model_sensitivity.json').read_text())
assert data['status'] == 'post_hoc_model_sensitivity'
labels = {'zero': '200 agents, zero drift', 'drain': '200 agents, draining',
          'accumulate': '200 agents, accumulating', 'steady': '3 agents, steady'}
keys = ['C_over_H20', 'C_over_HN', 'C_over_V_expiry', 'C_over_V_round_counterfactual']
rows = []
for cell in data['cells']:
    assert cell['equal_service_checks_passed']
    vals = []
    for key in keys:
        stat = cell['summary'].get(key)
        if stat is None:
            vals.append('--')
        else:
            assert stat['n'] == 24
            lo, hi = stat['mc95']
            vals.append(f"${stat['mean']:.3f}$\\newline $[{lo:.3f},{hi:.3f}]$")
    rows.append(labels[cell['cell']] + ' & ' + ' & '.join(vals) + r' \\')
text = r'''% Generated by audit/peer_review/render_sensitivity.py; do not edit.
\begin{table}[t]
\centering\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}>{\raggedright\arraybackslash}p{3.5cm}*{4}{>{\centering\arraybackslash}p{2.6cm}}@{}}
\toprule
Demand cell & $\Dur_C/\Dur_{20}$ & $\Dur_C/\Dur_N$ & $\Dur_C/\Dur_V$ expiry & $\Dur_C/\Dur_V$ next round \\
\midrule
''' + '\n'.join(rows) + r'''
\bottomrule
\end{tabular}
\caption{Post hoc sensitivity over 24 demand seeds per cell, with equal-service oracle sizing. Each cell shows the mean ratio and its 95\% Monte Carlo interval. All lifetimes are 4032 blocks; the next-round send-recovery column is counterfactual, and refreshes retain expiry locks. The intervals concern the specified model and generator. Group size $N$ is 200 in the first three rows and 3 in the last.}
\label{tab:sensitivity}
\end{table}
'''
(ROOT / 'paper/tex/review_sensitivity.tex').write_text(text)
print('Rendered paper/tex/review_sensitivity.tex from 96 verified cell/seed combinations')
